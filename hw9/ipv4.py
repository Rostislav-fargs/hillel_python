import re


def extract_ip_addresses(text: str) -> list[str]:
    """
    Виділяє всі IPv4-адреси з переданого тексту.

    Arguments:
        text (str): Вхідний текст, з якого потрібно витягнути IP-адреси.

    Returns:
        list[str]: Список знайдених IPv4-адрес.
    """
    pattern = re.compile(
        r'\b((?:25[0-5]|2[0-4][0-9]|1?[0-9]{1,2})\.'
        r'(?:25[0-5]|2[0-4][0-9]|1?[0-9]{1,2})\.'
        r'(?:25[0-5]|2[0-4][0-9]|1?[0-9]{1,2})\.'
        r'(?:25[0-5]|2[0-4][0-9]|1?[0-9]{1,2}))\b'
    )
    return pattern.findall(text)


if __name__ == "__main__":
    TEXT = """
        Сервери доступні за адресами 192.168.1.1 і 8.8.8.8.
        Некоректні IP: 999.999.999.999, 256.256.256.256, 1234.123.123.123.
    """
    print(extract_ip_addresses(TEXT))
